const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../src/app/static/dashboard-model.js'),'utf8'),sandbox);
const model=sandbox.window.lopmDashboardModel;
const symbols=[{symbol:'FPT',group:'Phần mềm'},{symbol:'ACB',group:'Ngân hàng'},{symbol:'BID',group:'Ngân hàng'}];
assert.deepEqual(Array.from(model.symbolsForGroup(symbols,'Ngân hàng'),r=>r.symbol),['ACB','BID']);
assert.equal(model.selectedSymbol(symbols,'Ngân hàng','FPT'),'ACB');
assert.equal(model.selectedSymbol(symbols,'Ngân hàng','BID'),'BID');
assert.equal(model.selectedSymbol(symbols,'all','FPT'),'FPT');
assert.equal(model.selectedSymbol(symbols,'Không có','FPT'),null);
assert.equal(model.connection({analysis:{mode:'saved'},phase_code:'closed'},true).label,'Dữ liệu phiên gần nhất');
assert.equal(model.connection({analysis:{mode:'saved'},phase_code:'lunch'},true).label,'Dữ liệu SSI đã lưu');
assert.equal(model.connection({analysis:{mode:'live'}},true).mode,'live');
assert.equal(model.connection({analysis:{mode:'live'}},false).mode,'reconnecting');
assert.equal(model.connection({analysis:{mode:'saved'},phase_code:'closed'},false).automatic,'Tự động thử lại');
assert.equal(model.connection({analysis:{mode:'waiting'}},true).mode,'waiting');
assert.equal(symbols.length,3);
console.log('Dashboard state: sector selection, live/saved/closed/waiting and real connection failure passed.');
